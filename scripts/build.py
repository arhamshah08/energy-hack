inject("guides/theme/README.md", "_Generated by `scripts/build.py`._\n\n### Loop frameworks and benchmarks\n\n"
       + table(harness, "", ("access", "kind")) + "\n### RSI papers\n\n" + table(rsi_papers, "", ("status",)))

